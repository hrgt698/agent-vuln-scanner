"""
services.demo — Demo 模式（无需 API Key 的 Mock 演示）
"""

import os
import time as _time
from datetime import datetime as _dt


def is_demo_mode() -> bool:
    """是否启用 Demo 模式"""
    return os.environ.get("IS_DEMO_MODE", "").lower() in {"true", "1", "yes"}


_DEMO_REPORT_TEMPLATE = """【教学演示 · 漏洞研判报告】
========================================
漏洞类型: {vuln_type}
风险等级: {risk}
评估时间: {timestamp}
========================================

【背景】
这是一个典型的 {vuln_type} 漏洞场景演示，用于教学环境中的
漏洞评估流程演练。报告内容由内置启发式引擎生成，不依赖外部大模型。

【风险要点】
1. 攻击者可通过构造恶意输入直接读取/执行敏感数据
2. 缺乏输入校验导致注入风险，需立即加固
3. 服务端响应回显过多内部信息，利于攻击者快速定位突破口
4. 无访问频率限制，可被暴力枚举或 DoS

【修复建议】
1. 对所有用户输入执行严格的白名单校验
2. 参数化查询 / 最小权限原则 / 命令调用封装
3. 错误信息统一通过错误码返回，避免堆栈泄露
4. 添加请求速率限制与登录失败锁定
5. 定期执行渗透测试与代码审计

【演示说明】
本报告为 IS_DEMO_MODE 模式下生成的模板化内容，不代表真实
目标的安全评估结论。如需获取真实研判结果，请取消 IS_DEMO_MODE
并配置有效的大模型 API Key。
"""


def generate_demo_report(vuln_data: dict) -> dict:
    """生成教学演示用 Mock 报告（无需 API Key）"""
    start = _time.time()
    vuln_type = str(vuln_data.get("cve_id") or vuln_data.get("vuln_name") or "未知漏洞")
    risk = str(vuln_data.get("risk_level") or "high")

    report = _DEMO_REPORT_TEMPLATE.format(
        vuln_type=vuln_type,
        risk=risk,
        timestamp=_dt.utcnow().strftime("%Y-%m-%dT%H:%M:%SZ"),
    )

    _now = _dt.utcnow().strftime("%Y-%m-%d %H:%M:%S UTC")
    report += (
        f"\n\n===== [演示报告元数据 · v3.3] =====\n"
        f"Generated by: 教学演示引擎（assessment-heuristic-demo-v3.3）\n"
        f"漏洞类型: {vuln_type}\n"
        f"风险等级: {risk}\n"
        f"评估时间: {_now}\n"
        f"说明: 本报告为教学演示内容，不代表任何真实目标的安全评估结论；"
        f"如需真实评估，请取消演示模式并配置 DashScope API Key"
    )

    latency_ms = int((_time.time() - start) * 1000) + 20
    return {
        "status": "demo",
        "model": "assessment-heuristic-demo-v3.3",
        "report": report,
        "latency_ms": latency_ms,
        "timestamp": _dt.utcnow().strftime("%Y-%m-%dT%H:%M:%SZ"),
        "vuln_type": vuln_type,
        "risk_level": risk,
    }